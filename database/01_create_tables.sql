-- Clean up existing tables in reverse dependency order if needed
BEGIN
    FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
        'APP_USER', 'PRICE_ALERT', 'SALE_TRANSACTION', 'PRICE_RECORD',
        'YIELD_RECORD', 'FRUIT_CROP', 'VEGETABLE_CROP', 'CEREAL_CROP',
        'CROP', 'MARKET', 'FIELD', 'FARMER'
    )) LOOP
        EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS PURGE';
    END LOOP;
END;
/

-- ----------------------------------------------------------------------------
-- 1. FARMER TABLE
-- Represents agricultural producers with landholdings and location.
-- ----------------------------------------------------------------------------
CREATE TABLE FARMER (
    farmer_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR2(100) NOT NULL,
    phone           VARCHAR2(15)  NOT NULL,
    village         VARCHAR2(100) NOT NULL,
    district        VARCHAR2(100) NOT NULL,
    land_area_acres NUMBER(8, 2)  NOT NULL,
    created_at      DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT chk_farmer_land_area CHECK (land_area_acres > 0)
);

COMMENT ON TABLE FARMER IS 'Master table holding farmer profiles and total land holdings';
COMMENT ON COLUMN FARMER.land_area_acres IS 'Total land area owned in acres (must be > 0)';

-- ----------------------------------------------------------------------------
-- 2. FIELD TABLE
-- Represents specific agricultural land parcels owned by a farmer (1:N).
-- ----------------------------------------------------------------------------
CREATE TABLE FIELD (
    field_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id       NUMBER        NOT NULL,
    location        VARCHAR2(150) NOT NULL,
    soil_type       VARCHAR2(50)  NOT NULL,
    area_acres      NUMBER(8, 2)  NOT NULL,
    created_at      DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_field_farmer FOREIGN KEY (farmer_id)
        REFERENCES FARMER(farmer_id) ON DELETE CASCADE,
    CONSTRAINT chk_field_area CHECK (area_acres > 0),
    CONSTRAINT chk_soil_type CHECK (soil_type IN ('Black Soil', 'Alluvial', 'Red Soil', 'Clay Loam', 'Sandy Loam'))
);

COMMENT ON TABLE FIELD IS 'Land parcels owned by farmers where crops are sown';

-- ----------------------------------------------------------------------------
-- 3. CROP TABLE (Superclass in EER Specialization)
-- General crop entities with name, broad category, and cultivation season.
-- ----------------------------------------------------------------------------
CREATE TABLE CROP (
    crop_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_name       VARCHAR2(100) NOT NULL,
    category        VARCHAR2(50)  NOT NULL,
    season          VARCHAR2(50)  NOT NULL,
    CONSTRAINT uk_crop_name UNIQUE (crop_name),
    CONSTRAINT chk_crop_category CHECK (category IN ('Cereal', 'Vegetable', 'Fruit', 'Pulse', 'Oilseed')),
    CONSTRAINT chk_crop_season CHECK (season IN ('Kharif', 'Rabi', 'Zaid', 'Perennial', 'All Season'))
);

COMMENT ON TABLE CROP IS 'Master table of agricultural crops (super-type for specialization)';

-- ----------------------------------------------------------------------------
-- 4. CROP SPECIALIZATIONS (1:1 Disjoint Subclasses)
-- Implements Extended Entity-Relationship (EER) specialization.
-- ----------------------------------------------------------------------------

-- 4a. Cereal Crop Subclass
CREATE TABLE CEREAL_CROP (
    crop_id            NUMBER PRIMARY KEY,
    avg_duration_days  NUMBER(4) NOT NULL,
    CONSTRAINT fk_cereal_crop FOREIGN KEY (crop_id)
        REFERENCES CROP(crop_id) ON DELETE CASCADE,
    CONSTRAINT chk_cereal_duration CHECK (avg_duration_days BETWEEN 60 AND 365)
);

COMMENT ON TABLE CEREAL_CROP IS 'EER Subclass: Grains/Cereals with maturity duration';

-- 4b. Vegetable Crop Subclass
CREATE TABLE VEGETABLE_CROP (
    crop_id            NUMBER PRIMARY KEY,
    perishability_days NUMBER(4) NOT NULL,
    CONSTRAINT fk_veg_crop FOREIGN KEY (crop_id)
        REFERENCES CROP(crop_id) ON DELETE CASCADE,
    CONSTRAINT chk_veg_perishability CHECK (perishability_days BETWEEN 1 AND 180)
);

COMMENT ON TABLE VEGETABLE_CROP IS 'EER Subclass: Vegetables with shelf life / perishability';

-- 4c. Fruit Crop Subclass
CREATE TABLE FRUIT_CROP (
    crop_id             NUMBER PRIMARY KEY,
    harvest_cycle_years NUMBER(3, 1) NOT NULL,
    CONSTRAINT fk_fruit_crop FOREIGN KEY (crop_id)
        REFERENCES CROP(crop_id) ON DELETE CASCADE,
    CONSTRAINT chk_fruit_cycle CHECK (harvest_cycle_years > 0 AND harvest_cycle_years <= 50)
);

COMMENT ON TABLE FRUIT_CROP IS 'EER Subclass: Fruits / Orchard crops with multi-year harvest cycles';

-- ----------------------------------------------------------------------------
-- 5. MARKET TABLE (Agricultural Produce Market Committees / Mandis)
-- ----------------------------------------------------------------------------
CREATE TABLE MARKET (
    market_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market_name     VARCHAR2(100) NOT NULL,
    district        VARCHAR2(100) NOT NULL,
    state           VARCHAR2(100) DEFAULT 'Maharashtra' NOT NULL,
    CONSTRAINT uk_market_district UNIQUE (market_name, district)
);

COMMENT ON TABLE MARKET IS 'Agricultural produce markets (APMC mandis)';

-- ----------------------------------------------------------------------------
-- 6. YIELD_RECORD TABLE
-- Historical and seasonal yield logs per field and crop.
-- Sowing vs. harvest date validation enforced by trigger trg_validate_harvest.
-- ----------------------------------------------------------------------------
CREATE TABLE YIELD_RECORD (
    yield_id           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    field_id           NUMBER        NOT NULL,
    crop_id            NUMBER        NOT NULL,
    sowing_date        DATE          NOT NULL,
    harvest_date       DATE          NOT NULL,
    expected_yield_qtl NUMBER(8, 2)  NOT NULL,
    actual_yield_qtl   NUMBER(8, 2)  NOT NULL,
    created_at         DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_yield_field FOREIGN KEY (field_id)
        REFERENCES FIELD(field_id) ON DELETE CASCADE,
    CONSTRAINT fk_yield_crop FOREIGN KEY (crop_id)
        REFERENCES CROP(crop_id) ON DELETE CASCADE,
    CONSTRAINT chk_expected_yield CHECK (expected_yield_qtl >= 0),
    CONSTRAINT chk_actual_yield CHECK (actual_yield_qtl >= 0)
);

COMMENT ON TABLE YIELD_RECORD IS 'Yield logs tracking expected vs. actual yield in quintals (qtl)';

-- ----------------------------------------------------------------------------
-- 7. PRICE_RECORD TABLE
-- Daily mandi prices per quintal for specific crops.
-- ----------------------------------------------------------------------------
CREATE TABLE PRICE_RECORD (
    price_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market_id       NUMBER        NOT NULL,
    crop_id         NUMBER        NOT NULL,
    price_date      DATE          NOT NULL,
    min_price       NUMBER(10, 2) NOT NULL,
    max_price       NUMBER(10, 2) NOT NULL,
    modal_price     NUMBER(10, 2) NOT NULL,
    created_at      DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_price_market FOREIGN KEY (market_id)
        REFERENCES MARKET(market_id) ON DELETE CASCADE,
    CONSTRAINT fk_price_crop FOREIGN KEY (crop_id)
        REFERENCES CROP(crop_id) ON DELETE CASCADE,
    CONSTRAINT chk_price_positive CHECK (min_price >= 0 AND max_price >= 0 AND modal_price >= 0),
    CONSTRAINT chk_price_order CHECK (min_price <= max_price),
    CONSTRAINT chk_modal_range CHECK (modal_price BETWEEN min_price AND max_price),
    CONSTRAINT uk_price_mkt_crop_date UNIQUE (market_id, crop_id, price_date)
);

COMMENT ON TABLE PRICE_RECORD IS 'Daily crop prices in rupees per quintal (min, max, modal)';

-- ----------------------------------------------------------------------------
-- 8. SALE_TRANSACTION TABLE
-- Realized sale records of farmers in specific mandis.
-- Total sale amount is a virtual computed column (quantity_qtl * price_per_qtl).
-- ----------------------------------------------------------------------------
CREATE TABLE SALE_TRANSACTION (
    sale_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id       NUMBER        NOT NULL,
    market_id       NUMBER        NOT NULL,
    crop_id         NUMBER        NOT NULL,
    quantity_qtl    NUMBER(8, 2)  NOT NULL,
    sale_date       DATE          NOT NULL,
    price_per_qtl   NUMBER(10, 2) NOT NULL,
    total_amount    NUMBER(12, 2) GENERATED ALWAYS AS (ROUND(quantity_qtl * price_per_qtl, 2)) VIRTUAL,
    created_at      DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT fk_sale_farmer FOREIGN KEY (farmer_id)
        REFERENCES FARMER(farmer_id) ON DELETE CASCADE,
    CONSTRAINT fk_sale_market FOREIGN KEY (market_id)
        REFERENCES MARKET(market_id) ON DELETE CASCADE,
    CONSTRAINT fk_sale_crop FOREIGN KEY (crop_id)
        REFERENCES CROP(crop_id) ON DELETE CASCADE,
    CONSTRAINT chk_sale_quantity CHECK (quantity_qtl > 0),
    CONSTRAINT chk_sale_price CHECK (price_per_qtl > 0)
);

COMMENT ON TABLE SALE_TRANSACTION IS 'Actual market sales recorded for farmers';

-- ----------------------------------------------------------------------------
-- 9. PRICE_ALERT TABLE
-- Generated automatically by database trigger when price deviation > 20%.
-- ----------------------------------------------------------------------------
CREATE TABLE PRICE_ALERT (
    alert_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_id         NUMBER        NOT NULL,
    market_id       NUMBER        NOT NULL,
    alert_date      DATE          NOT NULL,
    deviation_pct   NUMBER(6, 2)  NOT NULL,
    alert_message   VARCHAR2(255),
    created_at      TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT fk_alert_crop FOREIGN KEY (crop_id)
        REFERENCES CROP(crop_id) ON DELETE CASCADE,
    CONSTRAINT fk_alert_market FOREIGN KEY (market_id)
        REFERENCES MARKET(market_id) ON DELETE CASCADE
);

COMMENT ON TABLE PRICE_ALERT IS 'Automated alerts logged by database trigger for volatile price swings';

-- ----------------------------------------------------------------------------
-- 10. APP_USER TABLE (Authentication and RBAC)
-- Enforces role-based access for Farmer, Market Officer, and Admin.
-- ----------------------------------------------------------------------------
CREATE TABLE APP_USER (
    user_id         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR2(50)  NOT NULL,
    password_hash   VARCHAR2(255) NOT NULL,
    full_name       VARCHAR2(100) NOT NULL,
    role            VARCHAR2(20)  NOT NULL,
    farmer_id       NUMBER,
    market_id       NUMBER,
    is_active       NUMBER(1)     DEFAULT 1 NOT NULL,
    created_at      DATE          DEFAULT SYSDATE NOT NULL,
    CONSTRAINT uk_app_username UNIQUE (username),
    CONSTRAINT chk_user_role CHECK (role IN ('ADMIN', 'OFFICER', 'FARMER')),
    CONSTRAINT chk_user_active CHECK (is_active IN (0, 1)),
    CONSTRAINT fk_user_farmer FOREIGN KEY (farmer_id)
        REFERENCES FARMER(farmer_id) ON DELETE SET NULL,
    CONSTRAINT fk_user_market FOREIGN KEY (market_id)
        REFERENCES MARKET(market_id) ON DELETE SET NULL
);

COMMENT ON TABLE APP_USER IS 'Application user authentication and role mapping';
