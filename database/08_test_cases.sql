-- ============================================================================
-- FARMER-TO-MARKET CROP YIELD & PRICING DATABASE
-- ADBMS Mini-Project — Automated Database Test Suite
-- Script: 08_test_cases.sql
-- Description:
--   Executes automated validation for all required ADBMS database features:
--   1. Valid insertion of Farmer & Field
--   2. Foreign key violation rejection (ORA-02291)
--   3. Harvest date trigger rejection (trg_validate_harvest, -20001)
--   4. Negative yield CHECK constraint rejection (ORA-02290)
--   5. Invalid price ordering CHECK constraint (min_price > max_price)
--   6. Automatic price swing trigger (> 20% deviation logs PRICE_ALERT)
--   7. proc_best_market explicit cursor execution
--   8. fn_expected_revenue computation & safe zero fallback
--   9. Virtual total amount computation in SALE_TRANSACTION
--   10. Missing data / boundary handling
--   11. Role-based user check constraint validation
-- ============================================================================

SET SERVEROUTPUT ON SIZE UNLIMITED;
SET LINESIZE 180;
SET PAGESIZE 100;

-- ----------------------------------------------------------------------------
-- Create temporary test logging table
-- ----------------------------------------------------------------------------
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE TEST_RUN_LOG PURGE';
EXCEPTION
    WHEN OTHERS THEN NULL;
END;
/

CREATE TABLE TEST_RUN_LOG (
    test_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_name      VARCHAR2(100) NOT NULL,
    test_category  VARCHAR2(50)  NOT NULL,
    expected_rule  VARCHAR2(150) NOT NULL,
    status         VARCHAR2(10)  CHECK (status IN ('PASS', 'FAIL')),
    diagnostic_msg VARCHAR2(255)
);

-- ----------------------------------------------------------------------------
-- EXECUTE COMPREHENSIVE AUTOMATED TEST HARNESS
-- ----------------------------------------------------------------------------
DECLARE
    v_test_farmer_id NUMBER;
    v_test_field_id  NUMBER;
    v_mkt_id         NUMBER;
    v_mkt_name       VARCHAR2(100);
    v_price          NUMBER;
    v_result_str     VARCHAR2(255);
    v_rev            NUMBER;
    v_alert_count    NUMBER;
    v_sale_id        NUMBER;
    v_calc_total     NUMBER;
BEGIN
    DBMS_OUTPUT.PUT_LINE('================================================================');
    DBMS_OUTPUT.PUT_LINE('STARTING AUTOMATED ADBMS ORACLE TEST SUITE');
    DBMS_OUTPUT.PUT_LINE('================================================================');

    -- ------------------------------------------------------------------------
    -- TEST 1: Valid Farmer and Field Insertion
    -- ------------------------------------------------------------------------
    BEGIN
        INSERT INTO FARMER (name, phone, village, district, land_area_acres)
        VALUES ('Test Farmer Aniket', '9999900001', 'Test Village', 'Nashik', 4.5)
        RETURNING farmer_id INTO v_test_farmer_id;

        INSERT INTO FIELD (farmer_id, location, soil_type, area_acres)
        VALUES (v_test_farmer_id, 'Test Field East', 'Black Soil', 4.5)
        RETURNING field_id INTO v_test_field_id;

        INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES ('Valid Farmer & Field Insert', 'DML_INTEGRITY', 'Insert succeeds with valid PK/FK', 'PASS',
                'Farmer ID ' || v_test_farmer_id || ' and Field ID ' || v_test_field_id || ' inserted.');
    EXCEPTION
        WHEN OTHERS THEN
            INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
            VALUES ('Valid Farmer & Field Insert', 'DML_INTEGRITY', 'Insert succeeds with valid PK/FK', 'FAIL', SQLERRM);
    END;

    -- ------------------------------------------------------------------------
    -- TEST 2: Invalid Foreign Key Violation (FIELD referencing non-existent farmer)
    -- ------------------------------------------------------------------------
    BEGIN
        INSERT INTO FIELD (farmer_id, location, soil_type, area_acres)
        VALUES (888888, 'Ghost Parcel', 'Black Soil', 3.0);

        INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES ('Invalid Foreign Key', 'REFERENTIAL_INTEGRITY', 'Reject non-existent farmer_id (ORA-02291)', 'FAIL',
                'Unconstrained FK accepted an invalid farmer_id!');
    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE = -2291 THEN
                INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
                VALUES ('Invalid Foreign Key', 'REFERENTIAL_INTEGRITY', 'Reject non-existent farmer_id (ORA-02291)', 'PASS',
                        'Correctly rejected with ORA-02291 integrity constraint violation.');
            ELSE
                INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
                VALUES ('Invalid Foreign Key', 'REFERENTIAL_INTEGRITY', 'Reject non-existent farmer_id (ORA-02291)', 'FAIL',
                        'Unexpected error: ' || SQLERRM);
            END IF;
    END;

    -- ------------------------------------------------------------------------
    -- TEST 3: Trigger 1 (trg_validate_harvest) Rejection of Invalid Harvest Date
    -- Sowing date = 2026-05-10, Harvest date = 2026-04-10 (before sowing)
    -- ------------------------------------------------------------------------
    BEGIN
        INSERT INTO YIELD_RECORD (field_id, crop_id, sowing_date, harvest_date, expected_yield_qtl, actual_yield_qtl)
        VALUES (1, 1, TO_DATE('2026-05-10', 'YYYY-MM-DD'), TO_DATE('2026-04-10', 'YYYY-MM-DD'), 80, 85);

        INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES ('Trigger: trg_validate_harvest', 'PLSQL_TRIGGER', 'Raise -20001 when harvest <= sowing', 'FAIL',
                'Invalid harvest date was allowed without trigger exception!');
    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE = -20001 THEN
                INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
                VALUES ('Trigger: trg_validate_harvest', 'PLSQL_TRIGGER', 'Raise -20001 when harvest <= sowing', 'PASS',
                        'Correctly intercepted by trg_validate_harvest with error -20001.');
            ELSE
                INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
                VALUES ('Trigger: trg_validate_harvest', 'PLSQL_TRIGGER', 'Raise -20001 when harvest <= sowing', 'FAIL',
                        'Unexpected error code ' || SQLCODE || ': ' || SQLERRM);
            END IF;
    END;

    -- ------------------------------------------------------------------------
    -- TEST 4: CHECK Constraint on Negative Yield Rejection
    -- ------------------------------------------------------------------------
    BEGIN
        INSERT INTO YIELD_RECORD (field_id, crop_id, sowing_date, harvest_date, expected_yield_qtl, actual_yield_qtl)
        VALUES (1, 1, TO_DATE('2026-01-01', 'YYYY-MM-DD'), TO_DATE('2026-04-01', 'YYYY-MM-DD'), 80, -25.5);

        INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES ('Negative Yield Rejection', 'DOMAIN_INTEGRITY', 'Reject actual_yield_qtl < 0 (ORA-02290)', 'FAIL',
                'Negative yield was accepted!');
    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE = -2290 THEN
                INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
                VALUES ('Negative Yield Rejection', 'DOMAIN_INTEGRITY', 'Reject actual_yield_qtl < 0 (ORA-02290)', 'PASS',
                        'Correctly rejected with ORA-02290 check constraint violation.');
            ELSE
                INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
                VALUES ('Negative Yield Rejection', 'DOMAIN_INTEGRITY', 'Reject actual_yield_qtl < 0 (ORA-02290)', 'FAIL', SQLERRM);
            END IF;
    END;

    -- ------------------------------------------------------------------------
    -- TEST 5: CHECK Constraint on Invalid Price Ordering (min_price > max_price)
    -- ------------------------------------------------------------------------
    BEGIN
        INSERT INTO PRICE_RECORD (market_id, crop_id, price_date, min_price, max_price, modal_price)
        VALUES (1, 1, TRUNC(SYSDATE) + 50, 3500.00, 2500.00, 2800.00);

        INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES ('Invalid Price Constraint', 'DOMAIN_INTEGRITY', 'Reject min_price > max_price (ORA-02290)', 'FAIL',
                'Invalid price range was accepted!');
    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE = -2290 THEN
                INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
                VALUES ('Invalid Price Constraint', 'DOMAIN_INTEGRITY', 'Reject min_price > max_price (ORA-02290)', 'PASS',
                        'Correctly rejected with ORA-02290 check constraint.');
            ELSE
                INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
                VALUES ('Invalid Price Constraint', 'DOMAIN_INTEGRITY', 'Reject min_price > max_price (ORA-02290)', 'FAIL', SQLERRM);
            END IF;
    END;

    -- ------------------------------------------------------------------------
    -- TEST 6: Trigger 2 (trg_price_alert) Automatic Swing Detection
    -- ------------------------------------------------------------------------
    BEGIN
        SELECT COUNT(*) INTO v_alert_count
        FROM PRICE_ALERT
        WHERE crop_id = 3 AND market_id = 3 AND deviation_pct > 20;

        IF v_alert_count >= 1 THEN
            INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
            VALUES ('Trigger: trg_price_alert', 'PLSQL_TRIGGER', 'Auto-log alert when swing > 20%', 'PASS',
                    'Price alert automatically created with deviation > 20%.');
        ELSE
            INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
            VALUES ('Trigger: trg_price_alert', 'PLSQL_TRIGGER', 'Auto-log alert when swing > 20%', 'FAIL',
                    'No alert was logged for volatile price insert.');
        END IF;
    EXCEPTION
        WHEN OTHERS THEN
            INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
            VALUES ('Trigger: trg_price_alert', 'PLSQL_TRIGGER', 'Auto-log alert when swing > 20%', 'FAIL', SQLERRM);
    END;

    -- ------------------------------------------------------------------------
    -- TEST 7: Explicit Cursor Procedure (proc_best_market)
    -- ------------------------------------------------------------------------
    BEGIN
        proc_best_market(1, v_mkt_id, v_mkt_name, v_price, v_result_str);

        IF v_mkt_id IS NOT NULL AND v_price > 0 THEN
            INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
            VALUES ('Procedure: proc_best_market', 'PLSQL_PROCEDURE', 'Cursor returns highest 30d modal market', 'PASS',
                    'Best market for Wheat: ' || v_mkt_name || ' @ Rs.' || v_price || '/qtl');
        ELSE
            INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
            VALUES ('Procedure: proc_best_market', 'PLSQL_PROCEDURE', 'Cursor returns highest 30d modal market', 'FAIL',
                    'Procedure returned NULL or 0 price.');
        END IF;
    EXCEPTION
        WHEN OTHERS THEN
            INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
            VALUES ('Procedure: proc_best_market', 'PLSQL_PROCEDURE', 'Cursor returns highest 30d modal market', 'FAIL', SQLERRM);
    END;

    -- ------------------------------------------------------------------------
    -- TEST 8: Stored Function (fn_expected_revenue) & Zero Fallback
    -- ------------------------------------------------------------------------
    BEGIN
        -- Test existing farmer & crop (Farmer 1, Onion)
        v_rev := fn_expected_revenue(1, 2);

        -- Test non-existent farmer safely returns 0
        IF v_rev > 0 AND fn_expected_revenue(99999, 2) = 0 THEN
            INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
            VALUES ('Function: fn_expected_revenue', 'PLSQL_FUNCTION', 'Compute (Yield * Modal Price) & safe fallback', 'PASS',
                    'Expected revenue for Farmer 1: Rs.' || v_rev || '; non-existent farmer safely returned Rs.0');
        ELSE
            INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
            VALUES ('Function: fn_expected_revenue', 'PLSQL_FUNCTION', 'Compute (Yield * Modal Price) & safe fallback', 'FAIL',
                    'Calculated revenue returned invalid amount: ' || v_rev);
        END IF;
    EXCEPTION
        WHEN OTHERS THEN
            INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
            VALUES ('Function: fn_expected_revenue', 'PLSQL_FUNCTION', 'Compute (Yield * Modal Price) & safe fallback', 'FAIL', SQLERRM);
    END;

    -- ------------------------------------------------------------------------
    -- TEST 9: Virtual Column Calculation in SALE_TRANSACTION
    -- ------------------------------------------------------------------------
    BEGIN
        INSERT INTO SALE_TRANSACTION (farmer_id, market_id, crop_id, quantity_qtl, sale_date, price_per_qtl)
        VALUES (1, 1, 1, 20.00, TRUNC(SYSDATE), 2500.00)
        RETURNING sale_id, total_amount INTO v_sale_id, v_calc_total;

        IF v_calc_total = 50000.00 THEN
            INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
            VALUES ('Virtual Column: total_amount', 'SCHEMA_DESIGN', 'quantity_qtl * price_per_qtl auto-computed', 'PASS',
                    'Sale ID ' || v_sale_id || ': 20 qtl * Rs.2500 = Rs.' || v_calc_total);
        ELSE
            INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
            VALUES ('Virtual Column: total_amount', 'SCHEMA_DESIGN', 'quantity_qtl * price_per_qtl auto-computed', 'FAIL',
                    'Expected Rs.50000 but got ' || v_calc_total);
        END IF;
    EXCEPTION
        WHEN OTHERS THEN
            INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
            VALUES ('Virtual Column: total_amount', 'SCHEMA_DESIGN', 'quantity_qtl * price_per_qtl auto-computed', 'FAIL', SQLERRM);
    END;

    -- ------------------------------------------------------------------------
    -- TEST 10: Missing Data / Boundary Handling in proc_best_market
    -- ------------------------------------------------------------------------
    BEGIN
        proc_best_market(999999, v_mkt_id, v_mkt_name, v_price, v_result_str);

        IF v_mkt_id IS NULL AND v_price = 0 THEN
            INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
            VALUES ('Boundary: Missing Data Handling', 'EXCEPTION_HANDLING', 'Handle non-existent crop gracefully', 'PASS',
                    'Safely handled missing data: ' || v_result_str);
        ELSE
            INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
            VALUES ('Boundary: Missing Data Handling', 'EXCEPTION_HANDLING', 'Handle non-existent crop gracefully', 'FAIL',
                    'Did not return expected fallback for non-existent crop.');
        END IF;
    EXCEPTION
        WHEN OTHERS THEN
            INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
            VALUES ('Boundary: Missing Data Handling', 'EXCEPTION_HANDLING', 'Handle non-existent crop gracefully', 'FAIL', SQLERRM);
    END;

    -- ------------------------------------------------------------------------
    -- TEST 11: Role-Based User Check Constraint (APP_USER)
    -- ------------------------------------------------------------------------
    BEGIN
        INSERT INTO APP_USER (username, password_hash, full_name, role)
        VALUES ('hacker_user', 'hash123', 'Invalid User', 'SUPER_ADMIN');

        INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES ('RBAC Role Check Constraint', 'DOMAIN_INTEGRITY', 'Reject role NOT IN (ADMIN, OFFICER, FARMER)', 'FAIL',
                'Invalid role was accepted!');
    EXCEPTION
        WHEN OTHERS THEN
            IF SQLCODE = -2290 THEN
                INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
                VALUES ('RBAC Role Check Constraint', 'DOMAIN_INTEGRITY', 'Reject role NOT IN (ADMIN, OFFICER, FARMER)', 'PASS',
                        'Correctly rejected invalid role with ORA-02290.');
            ELSE
                INSERT INTO TEST_RUN_LOG (test_name, test_category, expected_rule, status, diagnostic_msg)
                VALUES ('RBAC Role Check Constraint', 'DOMAIN_INTEGRITY', 'Reject role NOT IN (ADMIN, OFFICER, FARMER)', 'FAIL', SQLERRM);
            END IF;
    END;

    -- Clean up test farmer and field created in Test 1 and sale in Test 9
    ROLLBACK;

END;
/

-- ----------------------------------------------------------------------------
-- DISPLAY FORMATTED TEST SUITE RESULTS
-- ----------------------------------------------------------------------------
PROMPT ================================================================================
PROMPT                        TEST EXECUTION SUMMARY
PROMPT ================================================================================

COL test_name FORMAT A30;
COL test_category FORMAT A22;
COL status FORMAT A6;
COL diagnostic_msg FORMAT A80;

SELECT test_name, test_category, status, diagnostic_msg
FROM TEST_RUN_LOG
ORDER BY test_id;

PROMPT ================================================================================
PROMPT TOTAL TESTS COUNT BY STATUS:
PROMPT ================================================================================
SELECT status, COUNT(*) AS count
FROM TEST_RUN_LOG
GROUP BY status;
