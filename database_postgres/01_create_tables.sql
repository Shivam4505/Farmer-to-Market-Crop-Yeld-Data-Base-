DROP TABLE IF EXISTS APP_USER CASCADE;
DROP TABLE IF EXISTS PRICE_ALERT CASCADE;
DROP TABLE IF EXISTS SALE_TRANSACTION CASCADE;
DROP TABLE IF EXISTS PRICE_RECORD CASCADE;
DROP TABLE IF EXISTS YIELD_RECORD CASCADE;
DROP TABLE IF EXISTS FRUIT_CROP CASCADE;
DROP TABLE IF EXISTS VEGETABLE_CROP CASCADE;
DROP TABLE IF EXISTS CEREAL_CROP CASCADE;
DROP TABLE IF EXISTS CROP CASCADE;
DROP TABLE IF EXISTS MARKET CASCADE;
DROP TABLE IF EXISTS FIELD CASCADE;
DROP TABLE IF EXISTS FARMER CASCADE;

-- 1. FARMER TABLE
CREATE TABLE FARMER (
    farmer_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(100) NOT NULL,
    phone           VARCHAR(15)  NOT NULL UNIQUE,
    village         VARCHAR(100) NOT NULL,
    district        VARCHAR(100) NOT NULL,
    land_area_acres NUMERIC(8, 2) NOT NULL CHECK (land_area_acres > 0),
    created_at      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 2. FIELD TABLE
CREATE TABLE FIELD (
    field_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id       INTEGER       NOT NULL REFERENCES FARMER(farmer_id) ON DELETE CASCADE,
    location        VARCHAR(150)  NOT NULL,
    soil_type       VARCHAR(50)   NOT NULL CHECK (soil_type IN ('Black Soil', 'Alluvial', 'Red Soil', 'Clay Loam', 'Sandy Loam')),
    area_acres      NUMERIC(8, 2) NOT NULL CHECK (area_acres > 0),
    created_at      TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 3. CROP TABLE (Superclass in EER Specialization)
CREATE TABLE CROP (
    crop_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_name       VARCHAR(100) NOT NULL UNIQUE,
    category        VARCHAR(50)  NOT NULL CHECK (category IN ('Cereal', 'Vegetable', 'Fruit', 'Pulse', 'Oilseed')),
    season          VARCHAR(50)  NOT NULL CHECK (season IN ('Kharif', 'Rabi', 'Zaid', 'Perennial', 'All Season'))
);

-- 4. CROP SPECIALIZATIONS (1:1 Disjoint Subclasses)
CREATE TABLE CEREAL_CROP (
    crop_id            INTEGER PRIMARY KEY REFERENCES CROP(crop_id) ON DELETE CASCADE,
    avg_duration_days  INTEGER NOT NULL CHECK (avg_duration_days BETWEEN 60 AND 365)
);

CREATE TABLE VEGETABLE_CROP (
    crop_id            INTEGER PRIMARY KEY REFERENCES CROP(crop_id) ON DELETE CASCADE,
    perishability_days INTEGER NOT NULL CHECK (perishability_days BETWEEN 1 AND 180)
);

CREATE TABLE FRUIT_CROP (
    crop_id             INTEGER PRIMARY KEY REFERENCES CROP(crop_id) ON DELETE CASCADE,
    harvest_cycle_years NUMERIC(3, 1) NOT NULL CHECK (harvest_cycle_years > 0 AND harvest_cycle_years <= 50)
);

-- 5. MARKET TABLE (APMC Mandis)
CREATE TABLE MARKET (
    market_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market_name     VARCHAR(100) NOT NULL,
    district        VARCHAR(100) NOT NULL,
    state           VARCHAR(100) DEFAULT 'Maharashtra' NOT NULL,
    CONSTRAINT uk_market_district UNIQUE (market_name, district)
);

-- 6. YIELD_RECORD TABLE
CREATE TABLE YIELD_RECORD (
    yield_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    field_id           INTEGER       NOT NULL REFERENCES FIELD(field_id) ON DELETE CASCADE,
    crop_id            INTEGER       NOT NULL REFERENCES CROP(crop_id) ON DELETE CASCADE,
    sowing_date        DATE          NOT NULL,
    harvest_date       DATE          NOT NULL,
    expected_yield_qtl NUMERIC(8, 2) NOT NULL CHECK (expected_yield_qtl >= 0),
    actual_yield_qtl   NUMERIC(8, 2) NOT NULL CHECK (actual_yield_qtl >= 0),
    created_at         TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 7. PRICE_RECORD TABLE
CREATE TABLE PRICE_RECORD (
    price_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    market_id       INTEGER        NOT NULL REFERENCES MARKET(market_id) ON DELETE CASCADE,
    crop_id         INTEGER        NOT NULL REFERENCES CROP(crop_id) ON DELETE CASCADE,
    price_date      DATE           NOT NULL,
    min_price       NUMERIC(10, 2) NOT NULL CHECK (min_price >= 0),
    max_price       NUMERIC(10, 2) NOT NULL CHECK (max_price >= 0),
    modal_price     NUMERIC(10, 2) NOT NULL CHECK (modal_price >= 0),
    quantity_qtl    NUMERIC(10, 2) DEFAULT NULL,
    remarks         VARCHAR(255)   DEFAULT NULL,
    created_at      TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT chk_price_order CHECK (min_price <= max_price),
    CONSTRAINT chk_modal_range CHECK (modal_price BETWEEN min_price AND max_price),
    CONSTRAINT uk_price_mkt_crop_date UNIQUE (market_id, crop_id, price_date)
);

-- 8. SALE_TRANSACTION TABLE (with Generated Total Column)
CREATE TABLE SALE_TRANSACTION (
    sale_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    farmer_id       INTEGER        NOT NULL REFERENCES FARMER(farmer_id) ON DELETE CASCADE,
    market_id       INTEGER        NOT NULL REFERENCES MARKET(market_id) ON DELETE CASCADE,
    crop_id         INTEGER        NOT NULL REFERENCES CROP(crop_id) ON DELETE CASCADE,
    quantity_qtl    NUMERIC(8, 2)  NOT NULL CHECK (quantity_qtl > 0),
    sale_date       DATE           NOT NULL,
    price_per_qtl   NUMERIC(10, 2) NOT NULL CHECK (price_per_qtl > 0),
    total_amount    NUMERIC(12, 2) GENERATED ALWAYS AS (ROUND(quantity_qtl * price_per_qtl, 2)) STORED,
    created_at      TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 9. PRICE_ALERT TABLE (Trigger-Generated)
CREATE TABLE PRICE_ALERT (
    alert_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    crop_id         INTEGER       NOT NULL REFERENCES CROP(crop_id) ON DELETE CASCADE,
    market_id       INTEGER       NOT NULL REFERENCES MARKET(market_id) ON DELETE CASCADE,
    alert_date      DATE          NOT NULL,
    deviation_pct   NUMERIC(6, 2) NOT NULL,
    alert_message   VARCHAR(255),
    created_at      TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 10. PRICE_AUDIT TABLE (Audit Trail for Seller Price Modifications)
CREATE TABLE PRICE_AUDIT (
    audit_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price_id        INTEGER        NOT NULL,
    market_id       INTEGER        NOT NULL REFERENCES MARKET(market_id) ON DELETE CASCADE,
    crop_id         INTEGER        NOT NULL REFERENCES CROP(crop_id) ON DELETE CASCADE,
    price_date      DATE           NOT NULL,
    action          VARCHAR(10)    NOT NULL CHECK (action IN ('INSERT', 'UPDATE', 'DELETE')),
    old_min_price   NUMERIC(10, 2),
    old_max_price   NUMERIC(10, 2),
    old_modal_price NUMERIC(10, 2),
    new_min_price   NUMERIC(10, 2),
    new_max_price   NUMERIC(10, 2),
    new_modal_price NUMERIC(10, 2),
    changed_by      VARCHAR(50)    DEFAULT 'SYSTEM' NOT NULL,
    changed_at      TIMESTAMP      DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 11. APP_USER TABLE (Authentication & Roles)
CREATE TABLE APP_USER (
    user_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username        VARCHAR(50)  NOT NULL UNIQUE,
    password_hash   VARCHAR(255) NOT NULL,
    full_name       VARCHAR(100) NOT NULL,
    role            VARCHAR(20)  NOT NULL CHECK (role IN ('ADMIN', 'OFFICER', 'FARMER')),
    farmer_id       INTEGER      REFERENCES FARMER(farmer_id) ON DELETE SET NULL,
    market_id       INTEGER      REFERENCES MARKET(market_id) ON DELETE SET NULL,
    is_active       SMALLINT     DEFAULT 1 NOT NULL CHECK (is_active IN (0, 1)),
    created_at      TIMESTAMP    DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 12. SELLER_MARKET_ASSIGNMENT TABLE (Authorized Mandis per Officer/Seller)
CREATE TABLE SELLER_MARKET_ASSIGNMENT (
    assignment_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         INTEGER   NOT NULL REFERENCES APP_USER(user_id) ON DELETE CASCADE,
    market_id       INTEGER   NOT NULL REFERENCES MARKET(market_id) ON DELETE CASCADE,
    assigned_at     TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT uk_seller_market UNIQUE (user_id, market_id)
);
