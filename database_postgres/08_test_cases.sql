-- ============================================================================
-- FARMER-TO-MARKET CROP YIELD & PRICING DATABASE
-- ADBMS Mini-Project — PostgreSQL Automated Test Suite
-- Script: database_postgres/08_test_cases.sql
-- ============================================================================

CREATE TABLE IF NOT EXISTS TEST_RUN_LOG (
    test_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_name VARCHAR(100) NOT NULL,
    test_category VARCHAR(50) NOT NULL,
    expected_rule VARCHAR(150) NOT NULL,
    status VARCHAR(10) CHECK (status IN ('PASS', 'FAIL')),
    diagnostic_msg VARCHAR(255)
);

DO $$
DECLARE
    v_test_farmer_id INTEGER;
    v_test_field_id INTEGER;
    v_mkt_id INTEGER;
    v_mkt_name VARCHAR(100);
    v_price NUMERIC(10, 2);
    v_result_str VARCHAR(255);
    v_rev NUMERIC(14, 2);
    v_missing_rev NUMERIC(14, 2);
    v_alert_count INTEGER;
    v_sale_id INTEGER;
    v_calc_total NUMERIC(12, 2);
BEGIN

    -- TEST 1: Valid Farmer and Field Insert
    BEGIN
        INSERT INTO FARMER
            (name, phone, village, district, land_area_acres)
        VALUES
            ('Test Farmer Aniket', '9999900001',
             'Test Village', 'Nashik', 4.5)
        RETURNING farmer_id INTO v_test_farmer_id;

        INSERT INTO FIELD
            (farmer_id, location, soil_type, area_acres)
        VALUES
            (v_test_farmer_id, 'Test Parcel', 'Black Soil', 4.5)
        RETURNING field_id INTO v_test_field_id;

        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES
            ('Valid Farmer & Field Insert', 'DML_INTEGRITY',
             'Insert succeeds with valid PK/FK', 'PASS',
             'Farmer ID ' || v_test_farmer_id || ' inserted.');

    EXCEPTION WHEN OTHERS THEN
        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES
            ('Valid Farmer & Field Insert', 'DML_INTEGRITY',
             'Insert succeeds with valid PK/FK', 'FAIL', SQLERRM);
    END;


    -- TEST 2: Foreign Key Violation
    BEGIN
        INSERT INTO FIELD
            (farmer_id, location, soil_type, area_acres)
        VALUES
            (-999999, 'Ghost Parcel', 'Black Soil', 3.0);

        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES
            ('Invalid Foreign Key', 'REFERENTIAL_INTEGRITY',
             'Reject non-existent farmer_id', 'FAIL',
             'Invalid foreign key was accepted.');

    EXCEPTION WHEN foreign_key_violation THEN
        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES
            ('Invalid Foreign Key', 'REFERENTIAL_INTEGRITY',
             'Reject non-existent farmer_id', 'PASS',
             'Correctly rejected invalid farmer ID.');

    WHEN OTHERS THEN
        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES
            ('Invalid Foreign Key', 'REFERENTIAL_INTEGRITY',
             'Reject non-existent farmer_id', 'FAIL', SQLERRM);
    END;


    -- TEST 3: Harvest Date Validation Trigger
    BEGIN
        INSERT INTO YIELD_RECORD
            (field_id, crop_id, sowing_date, harvest_date,
             expected_yield_qtl, actual_yield_qtl)
        VALUES
            (1, 1, DATE '2026-05-10', DATE '2026-04-10', 80, 85);

        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES
            ('Trigger: trg_validate_harvest', 'PLSQL_TRIGGER',
             'Reject harvest date <= sowing date', 'FAIL',
             'Invalid harvest date was accepted.');

    EXCEPTION WHEN OTHERS THEN
        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES
            ('Trigger: trg_validate_harvest', 'PLSQL_TRIGGER',
             'Reject harvest date <= sowing date', 'PASS',
             'Rejected invalid date: ' || SQLERRM);
    END;


    -- TEST 4: Negative Yield CHECK Constraint
    BEGIN
        INSERT INTO YIELD_RECORD
            (field_id, crop_id, sowing_date, harvest_date,
             expected_yield_qtl, actual_yield_qtl)
        VALUES
            (1, 1, DATE '2026-01-01', DATE '2026-04-01', 80, -25.5);

        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES
            ('Negative Yield Rejection', 'DOMAIN_INTEGRITY',
             'Reject actual_yield_qtl < 0', 'FAIL',
             'Negative yield was accepted.');

    EXCEPTION WHEN check_violation THEN
        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES
            ('Negative Yield Rejection', 'DOMAIN_INTEGRITY',
             'Reject actual_yield_qtl < 0', 'PASS',
             'Negative yield correctly rejected.');

    WHEN OTHERS THEN
        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES
            ('Negative Yield Rejection', 'DOMAIN_INTEGRITY',
             'Reject actual_yield_qtl < 0', 'FAIL', SQLERRM);
    END;


    -- TEST 5: Price Order Constraint
    BEGIN
        INSERT INTO PRICE_RECORD
            (market_id, crop_id, price_date,
             min_price, max_price, modal_price)
        VALUES
            (1, 1, CURRENT_DATE + 50,
             3500.00, 2500.00, 2800.00);

        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES
            ('Invalid Price Constraint', 'DOMAIN_INTEGRITY',
             'Reject min_price > max_price', 'FAIL',
             'Invalid price order was accepted.');

    EXCEPTION WHEN check_violation THEN
        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES
            ('Invalid Price Constraint', 'DOMAIN_INTEGRITY',
             'Reject min_price > max_price', 'PASS',
             'Invalid price order correctly rejected.');

    WHEN OTHERS THEN
        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES
            ('Invalid Price Constraint', 'DOMAIN_INTEGRITY',
             'Reject min_price > max_price', 'FAIL', SQLERRM);
    END;


    -- TEST 6: Price Alert Detection
    BEGIN
        SELECT COUNT(*)
        INTO v_alert_count
        FROM PRICE_ALERT
        WHERE crop_id = 3
          AND market_id = 3
          AND deviation_pct > 20;

        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES
            ('Trigger: trg_price_alert', 'PLSQL_TRIGGER',
             'Alert exists when deviation > 20%',
             CASE WHEN v_alert_count > 0 THEN 'PASS' ELSE 'FAIL' END,
             CASE WHEN v_alert_count > 0
                  THEN 'Matching price alert found.'
                  ELSE 'No matching alert exists.'
             END);

    EXCEPTION WHEN OTHERS THEN
        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES
            ('Trigger: trg_price_alert', 'PLSQL_TRIGGER',
             'Alert exists when deviation > 20%', 'FAIL', SQLERRM);
    END;


    -- TEST 7: Stored Procedure proc_best_market
    BEGIN
        CALL proc_best_market(
            1, v_mkt_id, v_mkt_name, v_price, v_result_str
        );

        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES
            ('Procedure: proc_best_market', 'PLSQL_PROCEDURE',
             'Cursor returns top market',
             CASE
                 WHEN v_mkt_name IS NOT NULL AND v_price > 0
                 THEN 'PASS'
                 ELSE 'FAIL'
             END,
             COALESCE(v_mkt_name, 'No market returned')
             || ' | Price: ' || COALESCE(v_price::TEXT, 'NULL'));

    EXCEPTION WHEN OTHERS THEN
        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES
            ('Procedure: proc_best_market', 'PLSQL_PROCEDURE',
             'Cursor returns top market', 'FAIL', SQLERRM);
    END;


    -- TEST 8: Stored Function fn_expected_revenue
    -- Explicitly call the three-argument overload to avoid ambiguity.
    BEGIN
        v_rev := public.fn_expected_revenue(
            1::INTEGER,
            2::INTEGER,
            1::NUMERIC
        );

        v_missing_rev := public.fn_expected_revenue(
            99999::INTEGER,
            2::INTEGER,
            1::NUMERIC
        );

        IF v_rev > 0 AND v_missing_rev = 0 THEN
            INSERT INTO TEST_RUN_LOG
                (test_name, test_category, expected_rule,
                 status, diagnostic_msg)
            VALUES
                ('Function: fn_expected_revenue',
                 'PLSQL_FUNCTION',
                 'Compute revenue with safe fallback',
                 'PASS',
                 'Revenue: Rs.' || v_rev
                 || '; missing farmer returned Rs.0.');
        ELSE
            INSERT INTO TEST_RUN_LOG
                (test_name, test_category, expected_rule,
                 status, diagnostic_msg)
            VALUES
                ('Function: fn_expected_revenue',
                 'PLSQL_FUNCTION',
                 'Compute revenue with safe fallback',
                 'FAIL',
                 'Revenue=' || COALESCE(v_rev::TEXT, 'NULL')
                 || '; missing farmer='
                 || COALESCE(v_missing_rev::TEXT, 'NULL'));
        END IF;

    EXCEPTION WHEN OTHERS THEN
        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule,
             status, diagnostic_msg)
        VALUES
            ('Function: fn_expected_revenue',
             'PLSQL_FUNCTION',
             'Compute revenue with safe fallback',
             'FAIL',
             SQLERRM);
    END;


    -- TEST 9: Generated total_amount in SALE_TRANSACTION
    BEGIN
        INSERT INTO SALE_TRANSACTION
            (farmer_id, market_id, crop_id, quantity_qtl,
             sale_date, price_per_qtl)
        VALUES
            (1, 1, 1, 20.00, CURRENT_DATE, 2500.00)
        RETURNING sale_id, total_amount
        INTO v_sale_id, v_calc_total;

        IF v_calc_total = 50000.00 THEN
            INSERT INTO TEST_RUN_LOG
                (test_name, test_category, expected_rule,
                 status, diagnostic_msg)
            VALUES
                ('Generated Column: total_amount',
                 'SCHEMA_DESIGN',
                 'quantity * price auto-computed',
                 'PASS',
                 'Sale ID ' || v_sale_id
                 || ': total Rs.' || v_calc_total);
        ELSE
            INSERT INTO TEST_RUN_LOG
                (test_name, test_category, expected_rule,
                 status, diagnostic_msg)
            VALUES
                ('Generated Column: total_amount',
                 'SCHEMA_DESIGN',
                 'quantity * price auto-computed',
                 'FAIL',
                 'Expected 50000; got '
                 || COALESCE(v_calc_total::TEXT, 'NULL'));
        END IF;

    EXCEPTION WHEN OTHERS THEN
        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule,
             status, diagnostic_msg)
        VALUES
            ('Generated Column: total_amount',
             'SCHEMA_DESIGN',
             'quantity * price auto-computed',
             'FAIL',
             SQLERRM);
    END;


    -- TEST 10: Invalid Application Role
    BEGIN
        INSERT INTO APP_USER
            (username, password_hash, full_name, role)
        VALUES
            ('bad_user_test', 'hash', 'Test User', 'SUPER_ADMIN');

        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES
            ('RBAC Role Check Constraint', 'DOMAIN_INTEGRITY',
             'Reject invalid role', 'FAIL',
             'Invalid role was accepted.');

        DELETE FROM APP_USER
        WHERE username = 'bad_user_test';

    EXCEPTION WHEN check_violation THEN
        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES
            ('RBAC Role Check Constraint', 'DOMAIN_INTEGRITY',
             'Reject invalid role', 'PASS',
             'Invalid role correctly rejected.');

    WHEN OTHERS THEN
        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES
            ('RBAC Role Check Constraint', 'DOMAIN_INTEGRITY',
             'Reject invalid role', 'FAIL', SQLERRM);
    END;


    -- TEST 11: Yield Summary View Availability
    BEGIN
        PERFORM 1
        FROM vw_crop_yield_summary
        LIMIT 1;

        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES
            ('Yield Summary View', 'VIEW_INTEGRITY',
             'View is queryable', 'PASS',
             'View query executed successfully.');

    EXCEPTION WHEN OTHERS THEN
        INSERT INTO TEST_RUN_LOG
            (test_name, test_category, expected_rule, status, diagnostic_msg)
        VALUES
            ('Yield Summary View', 'VIEW_INTEGRITY',
             'View is queryable', 'FAIL', SQLERRM);
    END;


    -- CLEANUP: Remove records created by Test 1 and Test 9
    IF v_test_field_id IS NOT NULL THEN
        DELETE FROM FIELD
        WHERE field_id = v_test_field_id;
    END IF;

    IF v_test_farmer_id IS NOT NULL THEN
        DELETE FROM FARMER
        WHERE farmer_id = v_test_farmer_id;
    END IF;

    IF v_sale_id IS NOT NULL THEN
        DELETE FROM SALE_TRANSACTION
        WHERE sale_id = v_sale_id;
    END IF;

END;
$$;


-- ============================================================================
-- DISPLAY ALL TEST RESULTS
-- ============================================================================

SELECT
    test_id,
    test_name,
    test_category,
    status,
    diagnostic_msg
FROM TEST_RUN_LOG
ORDER BY test_id;